    pg.evaluate("__askdir.S.showAll=false;__askdir.S.partMode=true")
    pg.evaluate("q=>__askdir.loadSpecific(q)", q)
    chk(not pg.is_visible('#zh') and pg.is_visible('#btn-reveal'), 'hidden sentence: reveal button takes the text place')
    chk(pg.is_visible('#btn-npart'), 'next-part button visible')
    n = len(q['parts'])
    for _ in range(n - 1): pg.click('#btn-npart')
    chk(not pg.is_visible('#btn-npart'), 'next-part hidden at last part')
    pg.evaluate("__askdir.submit()")
    chk(pg.is_visible('#zh'), 'text revealed after answering')
    chk(pg.inner_text('#zh').replace('\n','') == ''.join(x['tw'] for x in q['parts']), 'full text after answer')
    pg.evaluate("__askdir.S.showAll=false;__askdir.S.partMode=false;__askdir.S.phon='pinyin';__askdir.S.lang='es'")
    # --- reveal steps: hidden -> Chinese -> reading + translation ---
    pg.evaluate("q=>__askdir.loadSpecific(q)", q)
    chk(not pg.is_visible('#zh'), 'default: sentence hidden')
    chk(not pg.is_visible('#pyl') and not pg.is_visible('#trl'), 'default: no reading / translation')
    chk(pg.is_visible('#btn-reveal') and 'Ver texto' in pg.inner_text('#btn-reveal'), 'reveal button visible, with foreign text')
    h0 = pg.evaluate("document.querySelector('#sentcard').getBoundingClientRect().height")
    pg.click('#btn-reveal')
    chk(pg.inner_text('#zh').replace('\n','') == ''.join(x['tw'] for x in q['parts']), 'step 1 shows only the Chinese')
    chk(not pg.is_visible('#pyl') and not pg.is_visible('#trl'), 'step 1: still no reading / translation')
    chk(not pg.is_visible('#btn-reveal') and pg.is_visible('#btn-reveal2') and 'lectura' in pg.inner_text('#btn-reveal2'), 'step 1: second button offers reading + translation')
    pg.click('#btn-reveal2')
    chk(pg.is_visible('#pyl') and pg.is_visible('#trl'), 'step 2 shows reading and translation')
    chk(not pg.is_visible('#btn-reveal') and not pg.is_visible('#btn-reveal2'), 'reveal buttons gone at last step')
    h2 = pg.evaluate("document.querySelector('#sentcard').getBoundingClientRect().height")
    gap = pg.evaluate("document.querySelector('#pyl').getBoundingClientRect().top - document.querySelector('#btn-say').getBoundingClientRect().bottom")
    chk(gap >= 4, '聽 button and pinyin gap is %.1fpx' % gap)
    print('INFO sentence card height: hidden %.0f / all shown %.0f px' % (h0, h2))
    pg.evaluate("q=>__askdir.loadSpecific(q)", q)
    chk(not pg.is_visible('#zh'), 'next question hides the sentence again')
    pg.evaluate("__askdir.submit()")
    chk(pg.is_visible('#pyl') and pg.is_visible('#trl') and '🎧' not in pg.inner_text('#zh'), 'answering shows everything')
    pg.evaluate("__askdir.S.lang='zh';__askdir.S.phon='off'")
    pg.evaluate("q=>__askdir.loadSpecific(q)", q)
    pg.click('#btn-reveal')
    chk(not pg.is_visible('#btn-reveal') and not pg.is_visible('#btn-reveal2'), 'only-Chinese + no reading: one step only')
    pg.evaluate("__askdir.S.lang='es';__askdir.S.phon='pinyin';__askdir.S.showAll=true")
    pg.evaluate("q=>__askdir.loadSpecific(q)", q)
    chk(pg.is_visible('#pyl') and not pg.is_visible('#btn-reveal') and not pg.is_visible('#btn-reveal2'), '“text from the start” option shows everything at once')
    pg.evaluate("__askdir.S.partMode=false")
    # --- dictionary opens as a bottom sheet, label has foreign text, copyright cannot cover it ---
    chk('Vocabulario' in pg.inner_text('#btn-vocab'), 'dictionary button has foreign text')
    pg.click('#btn-vocab')
    chk(pg.is_visible('#vocab') and pg.locator('#vocab .g div').count() > 10, 'dictionary opens in the sheet')
    chk(pg.evaluate("(()=>{const r=document.querySelector('#modal .sheet').getBoundingClientRect();return r.top>=0&&r.bottom<=innerHeight+1})()"), 'dictionary sheet fits on screen')
    chk(pg.evaluate("(()=>{const c=document.querySelector('#hgCopy');if(!c)return true;const r=c.getBoundingClientRect();if(r.top>=innerHeight)return true;const e=document.elementFromPoint(r.left+r.width/2,r.top+Math.min(r.height/2,innerHeight-r.top-1));return !(e&&e.id==='hgCopy')})()"), 'copyright line is not drawn over the dictionary')
    chk(pg.evaluate("(()=>{const d=document.querySelector('#vocab .g div'),b=d.querySelector('b').getBoundingClientRect(),y=d.querySelector('.py').getBoundingClientRect();return Math.abs((b.top+b.bottom)/2-(y.top+y.bottom)/2)<b.height*0.6&&y.left>b.right-1})()"), 'dictionary: pinyin sits to the right of the Chinese')
    chk(pg.evaluate("parseFloat(getComputedStyle(document.querySelector('#vocab .g b')).fontSize)") >= 21, 'dictionary: Chinese is big')
    chk(pg.evaluate("(()=>{const d=document.querySelector('#vocab .g div'),b=d.querySelector('b').getBoundingClientRect(),f=d.querySelector('.fo').getBoundingClientRect();return f.top>=b.bottom-2})()"), 'dictionary: foreign text on the next line')
    print('INFO dictionary content height %d px' % pg.evaluate("document.querySelector('#vocab').scrollHeight"))
    pg.screenshot(path=SH + '/dict_sheet.png')
    pg.click('#m-close')
    chk(not pg.is_visible('#modal'), 'dictionary closes')
    # map filter + full game
    pg.evaluate("__askdir.S.map='night'")
    pg.evaluate("__askdir.startGame(3)")
    chk(pg.evaluate("__askdir.S.qs.every(q=>q.map==='night')") and pg.evaluate("__askdir.S.qs.length")==8, 'map filter, 8 questions')
    # photo onerror removes figure
    for i in range(8):
        qq = pg.evaluate("__askdir.S.q")
        for a in qq['actions']: pg.evaluate("a=>__askdir.act(a)", a)
        pg.evaluate("__askdir.submit()")
        if i == 0:
            pg.wait_for_timeout(300)
            chk(pg.locator('.photo').count() == 0, 'missing photo removed')
            pg.screenshot(path=SH + '/ok.png', full_page=True)
        pg.evaluate("__askdir.nextQuestion()")
    pg.wait_for_timeout(300)
    chk(pg.inner_text('#r-score') == '80', 'perfect round = 80')
    pg.screenshot(path=SH + '/result.png', full_page=True)
    lb = pg.evaluate("localStorage.getItem('askdir_lb')")
    chk('Ana' in (lb or ''), 'local leaderboard saved')
    # screenshots of a level-2 question with pinyin
    q2 = next(q for q in qs if q['level'] == 2 and q['crosses'])
    # 拼音注音四種都要真的測：畫面上有沒有出現拼音聲調字母／注音符號
    # （門檻：有顯示 ≥30 個；沒顯示時 ≤15，西班牙文的重音字母 ó é í 會佔幾個）
    PY = re.compile('[āáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜ]'); ZY = re.compile('[ㄅ-ㄩ]')
    for ph, want_py, want_zy in (('pinyin', True, False), ('zhuyin', False, True), ('both', True, True), ('off', False, False)):
        pg.evaluate("v=>{__askdir.S.phon=v}", ph)
        pg.evaluate("q=>__askdir.loadSpecific(q)", q2)
        for a in q2['actions'][:3]: pg.evaluate("a=>__askdir.act(a)", a)
        pg.wait_for_timeout(250)
        txt = pg.inner_text('body'); npy = len(PY.findall(txt)); nzy = len(ZY.findall(txt))
        chk((npy >= 30) == want_py and (npy <= 15 or want_py), '拼音注音=%s：拼音字母 %d 個，應該%s' % (ph, npy, '有' if want_py else '沒有'))
        chk((nzy >= 30) == want_zy and (nzy <= 15 or want_zy), '拼音注音=%s：注音符號 %d 個，應該%s' % (ph, nzy, '有' if want_zy else '沒有'))
        pg.screenshot(path=SH + '/l2_%s.png' % ph, full_page=True)
    pg.evaluate("__askdir.S.phon='pinyin'")
    pg.evaluate("q=>__askdir.loadSpecific(q)", q2)
    for a in q2['actions'][:3]: pg.evaluate("a=>__askdir.act(a)", a)
    pg.screenshot(path=SH + '/l2.png', full_page=True)
    pg.click('#btn-vocab'); pg.screenshot(path=SH + '/vocab.png', full_page=True); pg.click('#m-close')
    # map labels stay inside their 70x70 cards in every map, script and phonetic mode
    FIT = '''()=>{let bad=[];document.querySelectorAll('#map .bld').forEach(g=>{const c=g.querySelector('rect').getBoundingClientRect();
      g.querySelectorAll(':scope > text, :scope > g').forEach(e=>{const b=e.getBoundingClientRect();if(b.left<c.left-0.6||b.top<c.top-0.6||b.right>c.right+0.6||b.bottom>c.bottom+0.6)bad.push(g.dataset.k+':'+(e.textContent||'art').slice(0,8))})});return bad}'''
    nfit = 0; badfit = []
    for sc_ in ('trad', 'simp'):
        for ph_ in ('pinyin', 'zhuyin', 'both', 'off'):
            pg.evaluate("v=>{__askdir.S.script=v[0];__askdir.S.phon=v[1]}", [sc_, ph_])
            for mp in ['street','station','night','campus','hospital','metro','real']:
                qq = next(q for q in qs if q['map']==mp and q['level']==(5 if mp=='real' else 2))
                pg.evaluate("q=>__askdir.loadSpecific(q)", qq)
                bf = pg.evaluate(FIT); nfit += 1
                if bf: badfit.append('%s/%s/%s %s' % (sc_, ph_, mp, bf[:3]))
    chk(not badfit, 'map labels fit inside their cards (%d map/script/reading combos) %s' % (nfit, badfit[:3]))
    pg.evaluate("__askdir.S.script='trad';__askdir.S.phon='pinyin'")
    for mp in ['street','station','night','campus','hospital','metro','real']:
        qq = next(q for q in qs if q['map']==mp and q['level']==(5 if mp=='real' else 2))
        pg.evaluate("q=>__askdir.loadSpecific(q)", qq)
        pg.locator('.mapwrap').screenshot(path=SH + '/road_%s.png' % mp)
    # 看文字 and 聽 buttons share the same height
    pg.evaluate("q=>__askdir.loadSpecific(q)", q2)
    pg.evaluate("__askdir.S.showAll=false")
    pg.evaluate("q=>__askdir.loadSpecific(q)", q2)
    hs = pg.evaluate("()=>{const a=document.querySelector('#btn-reveal').getBoundingClientRect(),b=document.querySelector('#btn-say').getBoundingClientRect();return [a.height,b.height,a.width>0]}")
    chk(hs[2] and abs(hs[0]-hs[1]) <= 1.5, '看文字 and 聽 same height %s' % hs)
