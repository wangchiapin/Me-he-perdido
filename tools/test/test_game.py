    chk(abs(vh[0]-vh[1]) <= 1.5 and abs(vh[0]-vh[2]) <= 1.5 and vh[3] and vh[4] and not vh[5], 'vocab button between 看文字 and 聽, same height %s' % vh)
    pg.click('#btn-reveal')
    chk(pg.evaluate("document.querySelector('#btn-vocab').parentNode.id")=='tools' and pg.is_visible('#btn-vocab'), 'vocab button moves to the row under the sentence')
